import { test, expect } from "@playwright/test";
import axe from "axe-core";
import fs from "node:fs";
import path from "node:path";

const fixtureEmail = "irpa-browser-fixture-admin@example.test";
const fixturePassword = "FixtureOnly-Password-2026!";
const modules = [
  "Dashboard","Induction and Orientation","Induction Applications","Board Members Registration",
  "Members & Personnel","Invitations","Meetings","Meeting Room","Participants","Resolutions","Voting",
  "Actions","Documents","My Documents","Department Documents","Shared With Me","Signing Workspace",
  "Post-Signature Work","Final Archive","Upload Document","Retrieve Archived Documents","Signature Platform",
  "Decisions","Risk Register","Authorization & Approvals","Employee Payments",
  "Research, Statistics and Knowledge","Finance Portfolio","Procurement","Reports","Audit Trail",
  "Grant Intelligence & Funding Opportunities","Communication & Media","Downloads","Settings",
  "Add Administrator","Department and Archive Registry","Department Portal Builder",
  "External Auditor Portal","Auditors & Special Invitees","IT Operations"
];
const viewports = [
  {name:"desktop",width:1280,height:900},
  {name:"mobile",width:390,height:844}
];
const schemes = ["light","dark"];
const displayLabels = {"Induction and Orientation":"Induction & Orientation Portal","Induction Applications":"Induction Applications Portal","Board Members Registration":"Board Members Registration Portal","Members & Personnel":"Members & Personnel Portal","Meetings":"Meeting Portal","Meeting Room":"Meeting Room Portal","Participants":"Participants Portal","Resolutions":"Resolutions Portal","Voting":"Voting Portal","Actions":"Actions Portal","Documents":"Documents Portal","Signature Platform":"Signature Portal","Decisions":"Decisions Portal","Risk Register":"Risk Register Portal","Authorization & Approvals":"Authorization & Approvals Portal","Employee Payments":"Employee Payments Portal","Research, Statistics and Knowledge":"Research, Statistics and Knowledge Portal","Finance Portfolio":"Finance Portal","Procurement":"Procurement Portal","Reports":"Reports Portal","Audit Trail":"Audit Trail Portal","Downloads":"Downloads Portal","Settings":"Settings Portal","Add Administrator":"Add Administrator Portal","Department and Archive Registry":"Department and Archive Registry","Department Portal Builder":"Department Portal Builder","Grant Intelligence & Funding Opportunities":"Grant Intelligence & Funding Opportunities","Communication & Media":"Communication & Media Portal","IT Operations":"IT Operations Portal"};
const contrastFailures = [];
const pageCounts = [];
const opacityFindings = [];

function safe(value){return String(value??"").replace(/\|/g,"\\|").replace(/\r?\n/g," ").trim();}
function reportMarkdown(){
  const pageRows=pageCounts.map(x=>`| ${safe(x.page)} | ${x.before} | ${x.after} |`).join("\n");
  const failureRows=contrastFailures.map(x=>`| ${safe(x.page)} | ${safe(x.selector)} | ${safe(x.text)} | ${safe(x.foreground)} | ${safe(x.background)} | ${safe(x.ratio)} |`).join("\n");
  const opacityRows=opacityFindings.map(x=>`| ${safe(x.page)} | ${safe(x.selector)} | ${safe(x.text)} | ${safe(x.opacity)} | ${safe(x.foreground)} | ${safe(x.background)} |`).join("\n");
  return `# Cross-portal WCAG contrast audit

Generated by the authenticated Firebase-emulator Playwright fixture. The “before” column replays the legacy dark-theme text-token mapping on the same light portal surfaces; “after” is the actual shared-token implementation on this commit.

- Viewports: desktop 1280×900; mobile 390×844
- Color schemes: prefers-color-scheme light and dark
- Rule: axe-core color-contrast; WCAG AA 4.5:1 normal text and 3:1 large text
- Zero after-fix color-contrast failures are required for CI.

## Per-page failure counts

| Portal/page · viewport · scheme | Before (legacy token replay) | After |
|---|---:|---:|
${pageRows || "| (not scanned) | 0 | 0 |"}

## Failing elements after fix

| Page | Selector | Text | Foreground | Background | Contrast ratio |
|---|---|---|---|---|---:|
${failureRows || "| — | — | No color-contrast failures | — | — | — |"}

## Text opacity below 0.7

| Page | Selector | Text | Effective opacity | Foreground | Background |
|---|---|---|---:|---|---|
${opacityRows || "| — | — | None detected | — | — | — |"}
`;
}

test("WCAG contrast audit: every administrator portal at desktop/mobile in light/dark schemes", async ({ browser, baseURL }) => {
  test.setTimeout(1200000);
  for (const viewport of viewports) {
    for (const scheme of schemes) {
      const context = await browser.newContext({viewport:{width:viewport.width,height:viewport.height},colorScheme:scheme});
      const page = await context.newPage();
      await page.route("**/*", route => {
        const url = new URL(route.request().url());
        if (url.hostname === "localhost" || url.hostname === "127.0.0.1") return route.continue();
        return route.abort();
      });
      await page.goto(baseURL + "/");
      await page.locator('.auth-card input[type="email"]').fill(fixtureEmail);
      await page.locator('.auth-card input[type="password"]').fill(fixturePassword);
      await page.getByRole("button",{name:"Sign In Securely"}).click();
      await expect(page.locator(".topbar h2")).toBeVisible({timeout:30000});
      for (const module of modules) {
        const url = baseURL + "/?adminModule=" + encodeURIComponent(module);
        await page.goto(url);
        await expect(page.locator(".topbar h2")).toContainText(displayLabels[module] || module,{timeout:30000});
        await expect(page.locator("[data-active-portal-content]:visible").first()).toBeVisible({timeout:30000});
        await page.addScriptTag({content:axe.source});
        const pageLabel = module + " · " + viewport.name + " · " + scheme;
        const before = await page.evaluate(async () => {
          const style=document.createElement("style");
          style.id="legacy-dark-text-token-replay";
          style.textContent=`#root .app-shell .content-area:not(.dashboard-content-area) .page :where(.panel,.module-panel,.welcome-panel,.stat-card,.workflow-stage,.identity-card,.record-details,.detail-grid>div){--text:#f4f8f6!important;--text-muted:#b9cdc4!important;}`;
          document.head.appendChild(style);
          try { return await window.axe.run(document,{runOnly:{type:"rule",values:["color-contrast"]}}); }
          finally { style.remove(); }
        });
        const after = await page.evaluate(async () => window.axe.run(document,{runOnly:{type:"rule",values:["color-contrast"]}}));
        const beforeCount = before.violations.reduce((n,v)=>n+v.nodes.length,0);
        const afterNodes = after.violations.flatMap(v=>v.nodes.map(node=>{
          const data=node.any?.find(x=>x.data?.contrastRatio!==undefined)?.data||{};
          const selector=(node.target||[]).join(", ");
          const text=(node.html||"").replace(/<[^>]*>/g," ").replace(/\s+/g," ").slice(0,180);
          return {page:pageLabel,selector,text,foreground:data.fgColor||"(not reported)",background:data.bgColor||"(not reported)",ratio:data.contrastRatio==null?"(not reported)":String(data.contrastRatio)};
        }));
        const opacity = await page.evaluate(() => {
          const visible = el => {const r=el.getBoundingClientRect(),s=getComputedStyle(el);return r.width>0&&r.height>0&&s.visibility!=="hidden"&&s.display!=="none";};
          const nodes=[...document.querySelectorAll("body *")];
          return nodes.filter(el=>visible(el)&&String(el.textContent||"").trim()&&el.children.length===0).map(el=>{
            let effective=1,cur=el;
            while(cur&&cur!==document.documentElement){effective*=Number.parseFloat(getComputedStyle(cur).opacity||"1");cur=cur.parentElement;}
            if(effective>=.7)return null;
            const s=getComputedStyle(el);
            return {selector:el.tagName.toLowerCase()+(el.id?"#"+el.id:"")+(el.classList?.length?"."+[...el.classList].slice(0,3).join("."):""),text:String(el.textContent||"").trim().replace(/\s+/g," ").slice(0,140),opacity:Number(effective.toFixed(3)),foreground:s.color,background:s.backgroundColor};
          }).filter(Boolean);
        });
        pageCounts.push({page:pageLabel,before:beforeCount,after:afterNodes.length});
        contrastFailures.push(...afterNodes);
        opacityFindings.push(...opacity.map(x=>({...x,page:pageLabel})));
      }
      await context.close();
    }
  }
  const report=reportMarkdown();
  const target=path.resolve("docs/diagnostics/contrast-report.md");
  fs.mkdirSync(path.dirname(target),{recursive:true});
  fs.writeFileSync(target,report);
  if(process.env.GITHUB_STEP_SUMMARY)fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY,report+"\n");
  expect(contrastFailures, "WCAG AA color-contrast failures remain; see docs/diagnostics/contrast-report.md").toHaveLength(0);
});
